    /** Starts a sweep over the chunks an operator selected on the world map, and tells them how it went. */
    private static void pregenSelection(net.minecraft.server.level.ServerPlayer player, com.berg.orbis.net.PregenSelectionPayload payload) {
        net.minecraft.commands.CommandSourceStack source = player.createCommandSourceStack();
        if (!net.minecraft.commands.Commands.hasPermission(net.minecraft.commands.Commands.LEVEL_GAMEMASTERS).test(source)) {
            player.sendSystemMessage(net.minecraft.network.chat.Component.literal("Only operators can pre-generate."));
            return;
        }
        net.minecraft.server.level.ServerLevel level = player.level().getServer().overworld();
        if (!(level.getChunkSource().getGenerator() instanceof com.berg.orbis.worldgen.RealWorldChunkGenerator)) {
            player.sendSystemMessage(net.minecraft.network.chat.Component.literal("This world is not an Orbis Terrarum world."));
            return;
        }
        com.berg.orbis.worldgen.ChunkSelection selection = com.berg.orbis.worldgen.ChunkSelection.of(payload.shapes());
        System.out.println(String.format(java.util.Locale.ROOT, "[orbis] %s asked to pre-generate a map selection: %d shapes, %,d chunks",
                player.getName().getString(), payload.shapes().size(), selection.count()));
        player.sendSystemMessage(com.berg.orbis.worldgen.PregenTask.startSelection(level, selection, payload.skipSea()));
    }

